"""Generate secrets for the self-hosted Langfuse server and share its API keys.

Writes docker/langfuse/.env with random passwords and project API keys, then
adds the same API keys to the project .env so the agent can send traces.

Safe to re-run. Existing values are never replaced, because Postgres,
ClickHouse and Langfuse keep the credentials they were first started with.
To start over, run `pixi run langfuse-reset`.
"""

import secrets
import sys
from pathlib import Path

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
SERVER_ENV = ROOT / "docker" / "langfuse" / ".env"
AGENT_ENV = ROOT / ".env"

LOGIN_EMAIL = "dev@walkie.local"


def server_values() -> dict[str, str]:
    return {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_AUTH": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "SALT": secrets.token_hex(16),
        # Langfuse requires exactly 64 hex characters (256 bits).
        "ENCRYPTION_KEY": secrets.token_hex(32),
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_INIT_USER_EMAIL": LOGIN_EMAIL,
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_urlsafe(12),
    }


def write_server_env() -> dict[str, str]:
    if SERVER_ENV.exists():
        print(f"Keeping existing {SERVER_ENV.relative_to(ROOT)}")
        return {k: v or "" for k, v in dotenv_values(SERVER_ENV).items()}

    values = server_values()
    lines = [
        "# Generated by `pixi run langfuse-setup`. Do not commit.",
        "# The databases keep these credentials after first start, so do not",
        "# edit them by hand. Use `pixi run langfuse-reset` to start over.",
        *(f"{key}={value}" for key, value in values.items()),
    ]
    SERVER_ENV.write_text("\n".join(lines) + "\n")
    SERVER_ENV.chmod(0o600)
    print(f"Created {SERVER_ENV.relative_to(ROOT)}")
    return values


def update_agent_env(public_key: str, secret_key: str) -> None:
    wanted = {"LANGFUSE_PUBLIC_KEY": public_key, "LANGFUSE_SECRET_KEY": secret_key}
    current = dotenv_values(AGENT_ENV) if AGENT_ENV.exists() else {}

    mismatched = [k for k, v in wanted.items() if current.get(k) not in (None, "", v)]
    if mismatched:
        print(
            f"warning: {', '.join(mismatched)} in .env does not match the local "
            "Langfuse server. Remove those lines and re-run to use the local server.",
            file=sys.stderr,
        )
        return

    missing = {k: v for k, v in wanted.items() if not current.get(k)}
    if not missing:
        print(".env already has the Langfuse API keys")
        return

    text = AGENT_ENV.read_text() if AGENT_ENV.exists() else ""
    # Drop empty placeholders (KEY=) copied from .env.example before appending.
    kept = [
        line for line in text.splitlines() if line.split("=", 1)[0].strip() not in missing
    ]
    kept += ["", "# Local Langfuse server (added by `pixi run langfuse-setup`)"]
    kept += [f"{key}={value}" for key, value in missing.items()]
    AGENT_ENV.write_text("\n".join(kept).lstrip("\n") + "\n")
    print("Added LANGFUSE_PUBLIC_KEY and LANGFUSE_SECRET_KEY to .env")


def main() -> None:
    values = write_server_env()
    update_agent_env(
        values["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"],
        values["LANGFUSE_INIT_PROJECT_SECRET_KEY"],
    )
    print(
        "\nLangfuse UI: http://localhost:3000\n"
        f"  email:    {values['LANGFUSE_INIT_USER_EMAIL']}\n"
        f"  password: LANGFUSE_INIT_USER_PASSWORD in {SERVER_ENV.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
